import assert from 'node:assert/strict';
import {chooseBufferPolicy,learnPlaybackProfile,estimateEmergencyResumeMs} from '../buffer-adaptation.js';
const fresh=chooseBufferPolicy({},20);
assert.equal(fresh.startupMs,650);
assert.ok(fresh.resumeMs>=850);
const lag=learnPlaybackProfile({}, {speed:.42, audioSeconds:10, startupMs:650, underruns:3});
assert.equal(lag.cleanRuns,0);
assert.ok(lag.startupMs>650);
const next=chooseBufferPolicy(lag,20);
assert.ok(next.startupMs>10000,'A <1x generator must prebuffer enough for playback');
const worse=learnPlaybackProfile(lag,{speed:.25,audioSeconds:9,startupMs:next.startupMs,underruns:2});
assert.ok(worse.startupMs>=next.startupMs);
assert.ok(worse.resumeMs>lag.resumeMs);
const emergency=estimateEmergencyResumeMs({remainingAudioSec:30,speed:.3,baseResumeMs:1000});
assert.ok(emergency>10000 && emergency<=24000);
let clean=worse;
for(let i=0;i<5;i++)clean=learnPlaybackProfile(clean,{speed:1.4,audioSeconds:20,startupMs:clean.startupMs,underruns:0});
assert.ok(clean.cleanRuns>=4);
assert.ok(clean.startupMs<=worse.startupMs,'Clean high-speed runs can slowly shorten delay');
assert.equal(learnPlaybackProfile(clean,{speed:0,audioSeconds:0,underruns:7}).runs,clean.runs);
console.log('Adaptive buffer unit tests passed: speed, underrun, persistence and safe decay.');
